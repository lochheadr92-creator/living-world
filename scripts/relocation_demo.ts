import {mkdirSync,writeFileSync} from 'node:fs';
import {relocationFixture} from '../tests/helpers/relocation';
import {serializeWorld} from '../src/app/save';
import {stepWorld} from '../src/sim/world';
import {observe} from '../src/sim/knowledge';
import {perceive} from '../src/sim/perception';
import {conservationReport} from '../src/sim/economy';
import {setExternalController} from '../src/sim/external';
import {relOf} from '../src/sim/relations';
mkdirSync('civic_evidence',{recursive:true});
const f=relocationFixture(false),{w,a}=f;
const save=(name:string)=>writeFileSync(`civic_evidence/relocation-${name}-save.json`,serializeWorld(w));
f.run(a,':propose:');save('proposal');f.run(a,':prepare:');f.run(a,'eat_store:');f.run(a,'relocate-pack:');save('packing');
f.run(a,':depart:');f.choose(a,':travel:');for(let i=0;i<120;i++)stepWorld(w);save('travel');
for(let i=0;i<1200&&a.activity?.kind==='relocate';i++)stepWorld(w);perceive(w,a);f.run(a,':arrive:');f.run(a,'relocate-shelter:');
const site=w.sites.find(s=>s.hhId===a.hhId)!;observe(w,a,site);save('building');f.run(a,`haul:${site.id}`);f.run(a,`gather:${f.tree.id}`);f.run(a,`gather:${f.tree.id}`);f.run(a,`haul:${site.id}`);f.run(a,`build:${site.id}`);f.run(a,':found:');save('settled');
if(!conservationReport(w).ok)throw new Error('Conservation failed');
setExternalController(null);
const g=relocationFixture();g.run(g.a,':propose:');relOf(g.b!,g.a.id).trust=-40;g.run(g.a,':ask:');writeFileSync('civic_evidence/relocation-refused-save.json',serializeWorld(g.w));setExternalController(null);
console.log(JSON.stringify({staged:true,rules:w.settings.rulesVersion,tick:w.tick,phase:f.hh.relocations![0].phase,conservation:conservationReport(w).ok}));
