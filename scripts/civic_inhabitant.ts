import { readFileSync,writeFileSync,mkdirSync,existsSync } from 'node:fs';
import { deserializeWorld,serializeWorld } from '../src/app/save';
import { runLive,runReplay } from '../src/agent/run';
import { stubModel } from '../src/agent/model';
import { observationFromPrompt } from '../src/agent/protocol';
import { hashWorld,stepWorld } from '../src/sim/world';
import { conservationReport } from '../src/sim/economy';
const input=process.argv[2],out=process.argv[3],id=Number(process.argv[4]),tick=Number(process.argv[5]);
if(!input||!out||!id||!tick)throw new Error('checkpoint out personId startTick');
if(existsSync(out))throw new Error('Use a fresh output directory');
mkdirSync(out,{recursive:true});
const w=deserializeWorld(readFileSync(input,'utf8'));while(w.tick<tick)stepWorld(w);
const start=serializeWorld(w);writeFileSync(`${out}/start.json`,start);
const observations:NonNullable<ReturnType<typeof observationFromPrompt>>[]=[];
const model=stubModel('storehouse-inhabitant',req=>{
 const o=observationFromPrompt(req.user)!;observations.push(o);
 const option=o.options.find(a=>a.kind==='withdraw'&&a.target?.includes('storehouse'))??o.options[0];
 return JSON.stringify({choose:option.key,why:option.kind==='withdraw'?'Collect the useful goods from the store I know.':'Attend to my next available task.'});
});
const r=await runLive(w,id,model,{until:w.tick+900});
writeFileSync(`${out}/transcript.json`,JSON.stringify(r.transcript));
writeFileSync(`${out}/observations.json`,JSON.stringify(observations,null,2));
const replay=runReplay(deserializeWorld(start),r.transcript);
const storeChoices=r.transcript.calls.filter(c=>observations.some(o=>o.options.some(a=>a.kind==='withdraw'&&a.target?.includes('storehouse')&&a.key===('key' in c.choice?c.choice.key:'')))&&c.result?.status==='applied');
const success=storeChoices.some(c=>r.transcript.outcomes.some(result=>result.call===c.seq&&result.activityId===c.result?.activityId&&result.outcome==='success')&&observations.some(o=>o.doing.lastResult?.outcome==='success'&&o.doing.lastResult.t!==undefined&&o.doing.lastResult.t>=c.tick&&o.doing.lastResult.label===c.result?.label));
const report={storehouseChoices:storeChoices.length,success,hash:hashWorld(r.world),replayHash:hashWorld(replay.world),conservation:conservationReport(r.world),calls:r.transcript.calls};
writeFileSync(`${out}/report.json`,JSON.stringify(report,null,2));
if(!success||report.hash!==report.replayHash||!report.conservation.ok)throw new Error('Replay or conservation failure');
console.log({storehouseChoices:report.storehouseChoices,success,hash:report.hash,replayHash:report.replayHash,conservation:report.conservation});
